type launcherFixturePermit struct {
	Root, RootID, Nonce string
	Parent              processFixtureIdentity
}

func launcherFixturePeer(root string, permit launcherFixturePermit) (string, error) {
	executable, err := os.Executable()
	project, scopeErr := filepath.Abs(filepath.Join("..", ".."))
	rel, relErr := filepath.Rel(filepath.Join(project, "runtime", "qa", "auth-session-sidecar"), root)
	if err != nil || scopeErr != nil || relErr != nil || filepath.IsAbs(rel) || strings.Contains(rel, "..") || !strings.HasPrefix(filepath.Base(root), "run-") || !strings.EqualFold(filepath.Base(executable), "auth-session-process-fixture.exe") || !samePath(filepath.Dir(executable), filepath.Dir(root)) {
		return "", errors.New("synthetic launcher peer outside private QA scope")
	}
	id, err := processFixtureDirectoryID(root)
	parent, parentErr := processFixtureProcessIdentity(uint32(os.Getppid()))
	if err != nil || parentErr != nil || id != permit.RootID || permit.Root != root || parent != permit.Parent || len(permit.Nonce) != 64 || strings.Trim(permit.Nonce, "0123456789abcdef") != "" {
		return "", errors.New("synthetic launcher private parent grant invalid")
	}
	h, err := windows.OpenProcess(windows.PROCESS_QUERY_LIMITED_INFORMATION, false, parent.PID)
	if err != nil {
		return "", err
	}
	defer windows.CloseHandle(h)
	buffer := make([]uint16, 32768)
	size := uint32(len(buffer))
	if err = windows.QueryFullProcessImageName(h, 0, &buffer[0], &size); err != nil || !samePath(windows.UTF16ToString(buffer[:size]), executable) {
		return "", errors.New("synthetic launcher parent image invalid")
	}
	return executable, nil
}

// The synthetic executable creates no window and uses no browser or auth.
// It intentionally stays alive when its parent dies, exposing OS ownership
// rather than hiding a launcher gap behind cooperative child EOF handling.
func RunLauncherSyntheticChild(root string, input io.Reader) error {
	var permit launcherFixturePermit
	if err := json.NewDecoder(io.LimitReader(input, 4096)).Decode(&permit); err != nil {
		return err
	}
	if _, err := launcherFixturePeer(root, permit); err != nil {
		return err
	}
	for {
		time.Sleep(time.Hour)
	}
}

func RunLauncherSyntheticRoot(root string) error {
	// Scope is checked before reading a file; identity/grant is checked again
	// after decode. The one-use permit is generated by the authenticated worker.
	executable, err := os.Executable()
	project, scopeErr := filepath.Abs(filepath.Join("..", ".."))
	rel, relErr := filepath.Rel(filepath.Join(project, "runtime", "qa", "auth-session-sidecar"), root)
	if err != nil || scopeErr != nil || relErr != nil || strings.Contains(rel, "..") || filepath.IsAbs(rel) || !strings.HasPrefix(filepath.Base(root), "run-") || !samePath(filepath.Dir(executable), filepath.Dir(root)) {
		return errors.New("synthetic root scope invalid")
	}
	path := filepath.Join(root, "launcher-permit.json")
	info, err := os.Lstat(path)
	resolved, resolveErr := filepath.EvalSymlinks(path)
	if err != nil || resolveErr != nil || !info.Mode().IsRegular() || info.Size() > 4096 || !samePath(path, resolved) {
		return errors.New("synthetic root permit unavailable")
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	var permit launcherFixturePermit
	if json.Unmarshal(raw, &permit) != nil {
		return errors.New("synthetic root permit invalid")
	}
	executable, err = launcherFixturePeer(root, permit)
	if err != nil {
		return err
	}
	claim, err := os.OpenFile(filepath.Join(root, "launcher-permit-consumed"), os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
	if err != nil {
		return err
	}
	claim.Close()
	identity, err := processFixtureProcessIdentity(uint32(os.Getpid()))
	if err != nil {
		return err
	}
	child := exec.Command(executable, "--launcher-synthetic-child", root)
	child.SysProcAttr = &syscall.SysProcAttr{HideWindow: true}
	input, err := child.StdinPipe()
	if err != nil {
		return err
	}
	if err = child.Start(); err != nil {
		return err
	}
	childPermit := permit
	childPermit.Parent = identity
	if err = json.NewEncoder(input).Encode(childPermit); err != nil {
		child.Process.Kill()
		child.Wait()
		return err
	}
	childIdentity, err := processFixtureProcessIdentity(uint32(child.Process.Pid))
	if err != nil {
		child.Process.Kill()
		child.Wait()
		return err
	}
	receipt, err := os.OpenFile(filepath.Join(root, "launcher-child.json"), os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
	if err != nil {
		child.Process.Kill()
		child.Wait()
		return err
	}
	err = json.NewEncoder(receipt).Encode(processFixtureReceipt{LauncherRoot: identity, LauncherChild: childIdentity})
	receipt.Close()
	if err != nil {
		return err
	}
	for {
		time.Sleep(time.Hour)
	}
}

func runProcessFixtureLauncher(scanner *bufio.Scanner, encoder *json.Encoder, executable string, start processFixtureStart) error {
	parent, err := processFixtureProcessIdentity(uint32(os.Getpid()))
	if err != nil {
		return err
	}
	permit := launcherFixturePermit{Root: start.Grant.Root, RootID: start.Grant.RootID, Nonce: start.Grant.Nonce, Parent: parent}
	file, err := os.OpenFile(filepath.Join(permit.Root, "launcher-permit.json"), os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
	if err != nil {
		return err
	}
	err = json.NewEncoder(file).Encode(permit)
	file.Close()
	if err != nil {
		return err
	}
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	options := appshell.LaunchOptions{Executable: executable, UserDataDir: filepath.Join(permit.Root, "shared"), URL: "about:blank", ExtraArgs: []string{"--launcher-synthetic-root=" + permit.Root}}
	if start.StartupBarrier == "launcher_before_job" || start.StartupBarrier == "launcher_abort_before_job" {
		abort := errors.New("private fixture rejected suspended startup")
		var abortedRoot processFixtureIdentity
		_, err = appshell.LaunchUnassignedFixture(ctx, options, permit.Root, func(pid uint32, job, lifetime windows.Handle) error {
			identity, err := processFixtureProcessIdentity(pid)
			if err != nil {
				return err
			}
			h, err := windows.OpenProcess(windows.PROCESS_QUERY_LIMITED_INFORMATION|windows.SYNCHRONIZE, false, pid)
			if err != nil {
				return err
			}
			defer windows.CloseHandle(h)
			member, memberErr := chromeFixtureJobMembership(h, job)
			lifetimeMember, lifetimeErr := chromeFixtureJobMembership(h, lifetime)
			goMember, goErr := chromeFixtureJobMembership(windows.CurrentProcess(), lifetime)
			var flags uint32
			ok, _, _ := windows.NewLazySystemDLL("kernel32.dll").NewProc("GetHandleInformation").Call(uintptr(lifetime), uintptr(unsafe.Pointer(&flags)))
			if memberErr != nil || member || lifetimeErr != nil || !lifetimeMember || goErr != nil || !goMember || ok == 0 || flags&windows.HANDLE_FLAG_INHERIT != 0 {
				return errors.New("suspended startup ownership proof unavailable")
			}
			rootParent, parentErr := readerbroker.ParentPID(pid)
			pids, queryErr := (&chromeFixtureBridge{job: job}).jobPIDs()
			if parentErr != nil || rootParent != parent.PID || queryErr != nil || len(pids) != 0 {
				return errors.New("suspended startup lineage or empty inner Job invalid")
			}
			if _, err = os.Lstat(filepath.Join(permit.Root, "launcher-permit-consumed")); !os.IsNotExist(err) {
				return errors.New("suspended root executed before Job assignment")
			}
			if err = encoder.Encode(processFixtureReceipt{Stage: "launcher_unassigned", PID: parent.PID, LauncherRoot: identity, NodeMembershipKnown: true, LauncherLifetimeMember: true, LauncherLifetimeNoInherit: true}); err != nil {
				return err
			}
			if !scanner.Scan() {
				return errors.New("launcher barrier controller lost")
			}
			if start.StartupBarrier == "launcher_abort_before_job" && scanner.Text() == "abort" {
				abortedRoot = identity
				return abort
			}
			if scanner.Text() != "release" {
				return errors.New("launcher controller release invalid")
			}
			return nil
		})
		if start.StartupBarrier == "launcher_abort_before_job" {
			if !errors.Is(err, abort) || !appshell.FixtureStartupCleanupVerified(err) || abortedRoot.PID == 0 {
				return errors.New("private startup rejection did not return expected verified error")
			}
			if err = encoder.Encode(processFixtureReceipt{Stage: "launcher_aborted", PID: parent.PID, LauncherRoot: abortedRoot, CleanupVerified: true}); err != nil {
				return err
			}
			if !scanner.Scan() || scanner.Text() != "release" {
				return errors.New("aborted launcher controller lost")
			}
			return nil
		}
		return err
	}
	window, err := appshell.LaunchUnassignedFixture(ctx, options, permit.Root, nil)
	if err != nil {
		return err
	}
	receipt, err := waitLauncherFixtureReceipt(ctx, permit.Root)
	if err != nil || receipt.LauncherRoot.PID != uint32(window.PID()) || !appshell.FixtureOwnsLauncherPeers(window, nil, []uint32{receipt.LauncherRoot.PID, receipt.LauncherChild.PID}) {
		return errors.New("resumed actual Launch tree membership unavailable")
	}
	// A sibling worker uses the shared StartOwnedCommand path. Its separate
	// Job must survive CloseForRetry of the actual Launch window tree.
	workerRoot, err := os.MkdirTemp(filepath.Dir(permit.Root), "run-worker-")
	if err != nil {
		return err
	}
	workerPermit := permit
	workerPermit.Root = workerRoot
	workerPermit.RootID, err = processFixtureDirectoryID(workerRoot)
	if err != nil {
		return err
	}
	workerRaw, _ := json.Marshal(workerPermit)
	if err = os.WriteFile(filepath.Join(workerRoot, "launcher-permit.json"), workerRaw, 0600); err != nil {
		return err
	}
	command := exec.Command(executable, "--launcher-synthetic-root="+workerRoot)
	worker, err := appshell.StartOwnedCommand(command)
	if err != nil {
		return err
	}
	workerReceipt, err := waitLauncherFixtureReceipt(ctx, workerRoot)
	if err != nil || workerReceipt.LauncherRoot.PID != uint32(worker.PID()) || !appshell.FixtureOwnsLauncherPeers(nil, worker, []uint32{workerReceipt.LauncherRoot.PID, workerReceipt.LauncherChild.PID}) {
		return errors.New("resumed OwnedCommand tree membership unavailable")
	}
	receipt.Stage, receipt.PID = "launcher_resumed", parent.PID
	receipt.LauncherWorkerRoot, receipt.LauncherWorkerChild = workerReceipt.LauncherRoot, workerReceipt.LauncherChild
	receipt.LauncherTreeMembership, receipt.LauncherLifetimeMember = true, true
	if err = encoder.Encode(receipt); err != nil {
		return err
	}
	if !scanner.Scan() || scanner.Text() != "close-window" {
		return errors.New("resumed launcher controller lost")
	}
	closeCtx, closeCancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer closeCancel()
	if err = window.CloseForRetry(closeCtx); err != nil {
		return err
	}
	if !appshell.FixtureOwnsLauncherPeers(nil, worker, []uint32{workerReceipt.LauncherRoot.PID, workerReceipt.LauncherChild.PID}) {
		return errors.New("closing window affected sibling worker ownership")
	}
	receipt.Stage, receipt.LauncherIsolationVerified = "launcher_isolated", true
	if err = encoder.Encode(receipt); err != nil {
		return err
	}
	if !scanner.Scan() || scanner.Text() != "release" {
		return errors.New("isolated launcher controller lost")
	}
	return worker.CloseForRetry(closeCtx)
}

func waitLauncherFixtureReceipt(ctx context.Context, root string) (processFixtureReceipt, error) {
	for {
		var receipt processFixtureReceipt
		raw, err := os.ReadFile(filepath.Join(root, "launcher-child.json"))
		if err == nil && json.Unmarshal(raw, &receipt) == nil {
			return receipt, nil
		}
		select {
		case <-ctx.Done():
			return processFixtureReceipt{}, ctx.Err()
		case <-time.After(10 * time.Millisecond):
		}
	}
}
